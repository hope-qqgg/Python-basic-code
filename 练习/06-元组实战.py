# ------------------------------------------------------------
# 题目 5:综合挑战:学生成绩统计(元组嵌套)
# 用元组存 5 名学生,格式:("学号", "姓名", 语文, 数学, 英语)
#   ("S001", "王林", 85, 92, 78)
#   ("S002", "李慕婉", 92, 88, 95)
#   ("S003", "十三", 78, 85, 82)
#   ("S004", "曾牛", 88, 79, 91)
#   ("S005", "周轶", 95, 96, 89)
# 1. 打印每个人的总分和平均分(平均分保留2位小数)
# 2. 找出平均分最高的人(提示:边循环边比较)
# 3. 输出所有平均分大于 85 的人
# ------------------------------------------------------------
# 【小提示】
# 外层 for s in students: s 本身是一个元组
# s[2] 语文、s[3] 数学、s[4] 英语
# 找最高:top_avg = 0,循环里 if avg > top_avg 就更新
# 平均分保留2位:f"{avg:.2f}"

# 您的代码写在这里 ↓↓↓
students = (("S001", "王林", 85, 92, 78),("S002", "李慕婉", 92, 88, 95),("S003", "十三", 78, 85, 82),("S004", "曾牛", 88, 79, 91),("S005", "周轶", 95, 96, 89))
print("学号 \t 姓名 \t 总分 \t 平均分(平均分保留2位小数)")
for s in students:
    score = s[2] + s[3] + s[4]
    avg = score / 3
    print(f"{s[0]} \t {s[1]} \t {score} \t {avg:.2f}")

top_avg = 0
top_name = " "
for s in students:
    avg = (s[2] + s[3] + s[4]) / 3
    if avg > top_avg:
        top_avg = avg
        top_name = s[1]
print(f"平均分最高的人是：{top_name},{top_avg:.2f}分")

print("平均分大于 85 的人：")
for s in students:
    avg = (s[2] + s[3] + s[4]) / 3
    if avg > 85:
        print(s[1],round(avg,2))