# 您的代码写在这里 ↓↓↓
a = (100)
b = (100,)

print(type(a))  # <class 'int'>  ← 没有逗号,() 只是数学括号,所以是整数
print(type(b))  # <class 'tuple'> ← 加了逗号才是元组!

