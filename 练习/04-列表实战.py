# 题目 3:朋友名单管理(小菜单)
# 用列表存朋友名字,循环显示菜单:
#   1.查看名单  2.添加朋友  3.删除朋友  4.修改朋友  0.退出
# 根据输入执行对应操作
# ------------------------------------------------------------
# 【小提示】
# while True 死循环,break 退出
# 删除用 remove(按名字),修改用 列表[下标] = 新名字
# 查看时用 for 循环打印,带序号:for i, name in enumerate(名单)

# 您的代码写在这里 ↓↓↓
friends = ["小明", "小红", "小刚"]
while True:
    print("\n===== 朋友名单管理 =====")
    print("1.查看名单  2.添加朋友  3.删除朋友  4.修改朋友  0.退出")
    choice = input("请选择:")
    if choice == 1:
        if len(friends) == 0:
            print("当前朋友名单为空！")
        else:
            for i, name in enumerate(friends):
                print(f"{i + 1}.{name}")
    elif choice == 2:
        new_name = input("请输入新好友的名字：")
        friends.append(new_name)
        print(f"已添加新好友：{new_name}")
    elif choice == 3:
        del_name = input("请输入要删除好友的名字：")
        if del_name not in friends:
            friends.remove(del_name)
            print(f"已经删除好友：{del_name}")
    elif choice == 4:
        r_name = input("请输入要修改好友的名字：")
        if r_name not in friends:
            print(f"{r_name}不是你的好友")
        else:
            new_name = input(f"请输入{r_name}修改后的名字：")
            friends[friends.index(r_name)] = new_name
            print(f"已经把{r_name}修改为：{new_name}")
    elif choice == 0:
        print("正在退出")
        break
    else:
        print("错误输入")

