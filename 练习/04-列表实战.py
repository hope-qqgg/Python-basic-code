# 两个列表合并成一个,去掉重复元素,并从小到大排序输出
#   list1 = [3, 1, 4, 1, 5]
#   list2 = [9, 2, 6, 5, 3]
#   结果:[1, 2, 3, 4, 5, 6, 9]
# ------------------------------------------------------------
# 【小提示】
# list1 + list2 合并;用 in 判断去重(参考您之前的案例)
# 最后 .sort() 排序

# 您的代码写在这里 ↓↓↓
list1 = [3, 1, 4, 1, 5]
list2 = [9, 2, 6, 5, 3]
new_list = []
for num2 in list1 + list2:
    if num2 not in new_list:
        new_list.append(num2)
print(sorted(new_list))

