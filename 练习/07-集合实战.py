# ------------------------------------------------------------
# 题目 2:共同好友
# my_friends = {"小明", "小红", "小刚", "小丽"}
# your_friends = {"小刚", "小丽", "小强", "小华"}
# 1. 我们的共同好友(交集 &)
# 2. 全部好友去重(并集 |)
# 3. 只有我有、你没有的好友(差集 -)
# 4. 判断 "小红" 是不是我的好友(in 判断)
# ------------------------------------------------------------
# 【小提示】
# 交集 & / 并集 | / 差集 - 是集合最常用的三个操作
# 也可以用方法:intersection() / union() / difference()

# 您的代码写在这里 ↓↓↓
my_friends = {"小明", "小红", "小刚", "小丽"}
your_friends = {"小刚", "小丽", "小强", "小华"}
# 1. 我们的共同好友(交集 &)
common_friend = my_friends & your_friends
common_friend_2 = my_friends.intersection(your_friends)
print(f"我们的共同好友：{common_friend}")
print(f"我们的共同好友：{common_friend_2}")

# 2. 全部好友去重(并集 |)
all_friend = my_friends | your_friends
all_friend_2 = my_friends.union(your_friends)
print(f"我们的全部好友：{all_friend}")
print(f"我们的全部好友：{all_friend_2}")

# 3. 只有我有、你没有的好友(差集 -)
my_friends_not_your_friends = my_friends - your_friends
my_friends_not_your_friends_2 = my_friends.difference(your_friends)
print(f"只有我有、你没有的好友：{my_friends_not_your_friends}")
print(f"只有我有、你没有的好友：{my_friends_not_your_friends_2}")

# 4. 判断 "小红" 是不是我的好友(in 判断)
if "小红" in my_friends:
    print(f"'小红'是我的朋友")
else:
    print("f'小红'不是我的朋友")

