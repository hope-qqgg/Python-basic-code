# 题目 3:选课分析
# football = {"王林", "曾牛", "徐立国", "遁天"}
# basketball = {"张铁", "墨居仁", "王林", "曾牛"}
# 1. 同时选了两门课的人(交集)
# 2. 只选了足球、没选篮球的人(差集)
# 3. 全班一共有多少人参与了选课(并集的人数,用 len())
# ------------------------------------------------------------
# 【小提示】
# 输出交集/差集/并集
# 人数 = len(并集)

# 您的代码写在这里 ↓↓↓
football = {"王林", "曾牛", "徐立国", "遁天"}
basketball = {"张铁", "墨居仁", "王林", "曾牛"}

# 1. 同时选了两门课的人(交集)
football_basketball = football & basketball
print(f"同时选了两门课的人：{football_basketball}")

# 2. 只选了足球、没选篮球的人(差集)
only_football = football - basketball
print(f"只选了足球、没选篮球的人：{only_football}")

# 3. 全班一共有多少人参与了选课(并集的人数,用 len())
len_num = len(football | basketball)
print(f"全班一共有{len_num}人参与了选课")
