# 题目 5:综合挑战:朋友圈统计
# 三个人的好友集合:
#   a = {"王林", "曾牛", "韩立", "厉飞雨"}
#   b = {"曾牛", "韩立", "紫灵", "天运子"}
#   c = {"韩立", "紫灵", "厉飞雨", "云露"}
# 1. 三个人共同的好友
# 2. 出现在"至少两个人"朋友圈里的好友
#    (提示:两两交集,再合并: (a&b) | (a&c) | (b&c) )
# ------------------------------------------------------------
# 【小提示】
# 三人共同好友:a & b & c
# 至少两个人:两个集合的交集里都有 TA,把三组交集合并起来即可

# 您的代码写在这里 ↓↓↓
a = {"王林", "曾牛", "韩立", "厉飞雨"}
b = {"曾牛", "韩立", "紫灵", "天运子"}
c = {"韩立", "紫灵", "厉飞雨", "云露"}

# 1. 三个人共同的好友
print(f"三个人共同的好友：{a & b & c}")

# 2. 出现在"至少两个人"朋友圈里的好友
print(f'出现在"至少两个人"朋友圈里的好友：{a & b | b & c | a & c}')