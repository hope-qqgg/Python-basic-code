# ------------------------------------------------------------
# 题目 4:偶数和(continue 练习)
# 计算 1~50 之间所有偶数的和
# 要求:必须用 continue 跳过奇数
# ------------------------------------------------------------
# 【小提示】
# if i % 2 == 1: continue  ← 跳过奇数
# 其余数字累加

# 您的代码写在这里 ↓↓↓
num = 0
for i in range(1,51):
    if i % 2 == 1:
        continue
    num += i
print(num)

# ------------------------------------------------------------
# 题目 5:猜数字(简单版)
# 系统随机 1~50 的数字,用户猜,猜错提示"大了/小了"
# 猜对后输出一共猜了几次
# ------------------------------------------------------------
# 【小提示】
# random.randint(1, 50) 生成随机数
# 用一个 count 变量计数,每猜一次 count += 1

# 您的代码写在这里 ↓↓↓
# 生成随机数
import random
number = random.randint(1,50)
num_1 = 0
count = 0
while True:
    num_1 = int(input("请输入你觉得正确的数字："))
    if num_1 > number:
        print("猜大了")
        count += 1
        continue
    elif num_1 < number:
        print("猜小了")
        count += 1
        continue
    else:
        count += 1
        break
print(f"恭喜你猜对了是{number},一共用了{count}次")

