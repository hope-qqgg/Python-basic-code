# 题目 1:1~100 求和
# 用 for 循环 和 while 循环 各写一遍,输出结果(答案:5050)
# ------------------------------------------------------------
# 【小提示】
# 需要一个"累加变量",每循环一次就往里加
# for:for i in range(1, 101)
# while:定义 i = 1,循环里 i += 1

# 您的代码写在这里 ↓↓↓
# while循环
i = 0
num_sum = 0
while i <= 100:
    num_sum += i
    i += 1
print(num_sum)
print("------------------------------")

# for循环
num2_sum = 0
for j in range(1,101):
    num2_sum += j
print(num2_sum)
print("------------------------------")

# ------------------------------------------------------------
# 题目 2:九九乘法表
# 输出如下(前3行示例):
#   1x1=1
#   1x2=2 2x2=4
#   1x3=3 2x3=6 3x3=9
# ------------------------------------------------------------
# 【小提示】
# 需要两层循环:外层控制行(1~9),内层控制列(1~当前行数)
# print(..., end="\t") 可以不换行,print() 单独一行用来换行
# 内层循环范围是 range(1, i + 1),想一想为什么

# 您的代码写在这里 ↓↓↓
for i in range(1,10): #外层控制行
    for j in range(1,i+1):
        print(f"{j} * {i} = {j*i}",end="\t")
    print()
print("------------------------------")

