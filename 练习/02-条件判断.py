# ------------------------------------------------------------
# 题目 2:判断闰年
# 输入一个年份,输出它是不是闰年
# 闰年规则:能被4整除 且 不能被100整除;或者 能被400整除
# ------------------------------------------------------------
# 【小提示】
# 整除用 %,条件组合用 and / or
# 例:2000 是闰年,1900 不是闰年,2024 是闰年

# 您的代码写在这里 ↓↓↓
# 1.输入年份
year = int(input("请输入一个年份："))

# 2.判断（闰年规则:能被4整除 且 不能被100整除;或者 能被400整除）
if (year % 4 == 0 and year % 100 != 0) or year % 400 == 0:
    print(f"{year}是闰年")
else:
    print(f"{year}是平年")

# ------------------------------------------------------------
# 题目 3:星期翻译机(match 练习)
# 输入 1~7,输出对应:1→周一,2→周二 ... 7→周日
# 输入其他数字,输出:输入错误
# ------------------------------------------------------------
# 【小提示】
# 用 match 数字: case 1: ...;末尾记得加 case _: 兜底
# 不用写 break,match 不会"穿透"

# 您的代码写在这里 ↓↓↓
# 1.输入数字
num = int(input("输入1~7:"))

# 2.匹配
match num:
    case 1:
        print("周一")
    case 2:
        print("周二")
    case 3:
        print("周三")
    case 4:
        print("周四")
    case 5:
        print("周五")
    case 6:
        print("周六")
    case 7:
        print("周日")
    case _:
        print("输入错误")

# ------------------------------------------------------------
# 题目 4:简易计算器
# 输入两个数字和一个运算符(+ - * /),输出计算结果
# 例:输入 8、2、+ → 输出 10.0
# 除法注意:除数不能为0,如果为0输出"除数不能为0"
# ------------------------------------------------------------
# 【小提示】
# 先用 if 判断运算符,或者用 match
# 除数为 0 时程序会报错,记得提前判断

# 您的代码写在这里 ↓↓↓

while True:
    # 1.输入两个数字
    num1 = float(input("请输入第一个数："))
    num2 = float(input("请输入第二个数："))

    # 2.判断（除数不能为0）
    if num2 == 0:
        print("除数不能为0")
        continue
    else:
        # 3.运算符(+ - * /)
        operator = input("运算符(+ - * /):")
        # 3.匹配
        match operator:
            case "+":
                print(f"{num1} + {num2} = {num1 + num2}")
                break
            case "-":
                print(f"{num1} - {num2} = {num1 - num2}")
                break
            case "*":
                print(f"{num1} * {num2} = {num1 * num2}")
                break
            case "/":
                print(f"{num1} / {num2} = {num1 / num2}")
                break
            case _:
                print("输入错误")
                continue
