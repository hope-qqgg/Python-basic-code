#
# 【这个文件在干什么】
#   上一课 01 只是让一个函数变成一个网址。这一课要让网址「会说话」：
#   客户端能告诉服务端「我要哪一个」「我要按什么条件筛」。
#   文件里 3 个路由，正好覆盖 3 种传信息的方式：
#
#       网址                          类型        客户端怎么给值
#       GET /book                     静态路由    什么都不用给
#       GET /book/search?keyword=网络  查询参数    写在问号后面（key=value）
#       GET /book/2                   路径参数    直接塞进网址路径里
#
# 【必须先懂的 5 个词】
#   1. 路由(route)    —— 一条「网址 + 请求方法 对 一个函数」的登记项
#   2. 装饰器         —— 写在函数头顶的 @app.get("/xxx")，作用就是「把这行网址登记给它」
#   3. 路径参数       —— 网址里用 {name} 挖的洞，客户端填什么，函数就收到什么
#   4. 查询参数       —— 问号后面 key=value，多个用 & 连，顺序无所谓
#   5. 422            —— 参数类型不对，框架在调用你的函数「之前」就拦下了
#
# 【读文件的顺序】
#   ① 先看 books（原文件第 5 行往下）—— 它是这个文件的假数据库
#   ② 再看 3 个路由：先 /book，再 /book/search，最后 /book/{book_id}
#   ③ 最后看文件末尾的启动段（原文件第 29 行往下）
#
# ⚠️ 一行重要说明：本文件里凡是提到「第 N 行」，指的都是【原文件
#    02_路由与参数.py】的行号，不是这个注释版的行号（注释版插了注释，行号整体后移）。
#
# 【先记住一句话】
#   本章所有「测一下」都可以在 http://127.0.0.1:8000/docs 里点着做，
#   不用 Postman、不用手写 curl。
# ============================================================================

# ① 从 fastapi 包里导入 FastAPI 这个类 —— 它是整个框架的入口。

from fastapi import FastAPI

# ② 创建一个 app 对象。
#    可以把它想成「一张空的登记表」：后面每个 @app.get / @app.post
#    都往这张表上加一行。uvicorn 启动服务时，拿的就是这个 app。
#
#    括号里还能写 FastAPI(title="路由与参数练习") —— 那样 /docs 页面的标题会变成
#    你写的名字，不改也能用，默认叫 FastAPI。

app = FastAPI()

# ③ 假数据库：一个列表，里面 4 个字典，每个字典就是一条书。
#    真项目里这一层是 SQL 查询（第 11 周接 MySQL），现在先用内存列表顶上，
#    对接口来说效果是一样的 —— 反正都是「返回一堆数据」。
#
#    字段：id 唯一编号 / title 书名 / author 作者
#    注意这是一层 List[Dict]，所以后面用 b["title"] 这种取法，不是 b.title。

books = [
    {"id": 1, "title": "Python编程", "author": "张三"},
    {"id": 2, "title": "数据库原理", "author": "李四"},
    {"id": 3, "title": "计算机网络", "author": "王五"},
    {"id": 4, "title": "网络安全", "author": "赵六"},
]

# ============================================================================
# 路由一：GET /book  ——  静态路由（最简单的一种）
# ----------------------------------------------------------------------------
# 「静态」= 这个网址里一个洞都没有，是死的一条。
# 客户端除了访问它，什么都传不进来，你也就只能返回全部数据。
#
# 实测（本机 venv 真起服务，不是推断）：
#     GET /book  →  200
#     [{"id":1,"title":"Python编程","author":"张三"},
#      {"id":2,"title":"数据库原理","author":"李四"},
#      {"id":3,"title":"计算机网络","author":"王五"},
#      {"id":4,"title":"网络安全","author":"赵六"}]
#
# 注意：你 return 的是 Python 的 list，客户端收到的却是 JSON 文本 ——
#       这一步转换是 FastAPI 替你做的，一行 json.dumps 都不用写。
# ============================================================================

# 装饰器里的 "/book" 就是网址本体；@app.get 表示「这条网址只接受 GET」。
#
# ⚠️ 网址开头那个斜杠 "/" 必须写。写成 @app.get("book") 的话：
#    服务照样启动、/docs 里也能看到，但你去访问 /book 就是 404。
#    这是新手最容易踩且最难查的一个坑（启动不报错、日志没红字）。

@app.get("/book")
def get_book():
    # 函数返回什么，客户端就收到什么。这里直接把整个列表返回去。

    return books

# ============================================================================
# 路由二：GET /book/search  ——  查询参数（问号后面的东西）
# ----------------------------------------------------------------------------
# 🔴🔴 本文件最重要的一条：这段必须写在下面 /book/{book_id} 的「前面」！
#
#    FastAPI 是按「从上往下」的顺序去匹配路由的。
#    你把这两段调换位置，访问 /book/search 时，"search" 会先被
#    /book/{book_id} 抓走，然后框架试着把 "search" 转成 int，转不动，回 422。
#    实测原话长这样：
#      {"detail":[{"type":"int_parsing","loc":["path","book_id"],
#        "msg":"Input should be a valid integer, unable to parse string as an integer",
#        "input":"search"}]}
#
#    口诀：越「具体」的网址，越要排在越前面。
#
# 【查询参数的规则 —— 只看有没有默认值】
#    有默认值 → 可选（不传就用默认值）
#    无默认值 → 必填（不传就 422）
#    这里 4 个参数全都有默认值，所以一个都不传也能访问。
#
# 实测 4 种用法：
#    /book/search                    →  200  total 4，全部 4 本
#    /book/search?keyword=网络        →  200  total 2（计算机网络、网络安全）
#    /book/search?author=张           →  200  total 1（张三那本）
#    /book/search?page=2&size=2       →  200  data 是第 3、4 本
# ============================================================================

# 参数后面的 :str / :int 不是装饰品 —— 是真校验。
# 客户端传 page=abc，框架直接回 422，你的函数根本不会被执行。
#
# 这一点跟你之前学的「类型标注只是给人看的」正好相反。区别在于：
#     普通 Python 函数里的标注 —— 运行时没人管
#     FastAPI 路由函数里的标注 —— 框架拿它当校验规则用

@app.get("/book/search")
def search_book(keyword:str = "",author:str = "", page:int = 1, size:int = 10):
    # 一行同时做两件事：过滤 + 收集。
    # 拆开看等价于：
    #     result = []
    #     for b in books:
    #         if keyword in b["title"] and author in b["author"]:
    #             result.append(b)
    #
    #   keyword in b["title"]   →  书名里「含有」这几个字（不是相等！）
    #   author  in b["author"]  →  作者里含有
    #   两个用 and 连起来     →  必须同时满足
    #
    # ⭐ 为什么 keyword 不填也照样返回全部？这是「空字符串」的妙处：
    #      "" in "Python编程"  →  True      （空字符串在任何一个字符串里）
    #    所以不填时每个条件都为真，过滤等于没过滤 —— 可选参数最省事的写法。
    #    反过来，如果写成 keyword == b["title"]，不填时就一本都查不到了。

    result = [b for b in books if keyword in b["title"] and author in b["author"]]
    # 分页的核心就这一行：算出「这一页从第几个元素开始切」。
    #     page=1 → (1-1)*10 = 0    从下标 0 开始
    #     page=2 → (2-1)*10 = 10   从下标 10 开始
    #     page=3 → (3-1)*10 = 20   从下标 20 开始
    #
    # 为什么要减 1？因为页码是「人话」，从 1 开始数；
    # 而下标是「电脑话」，从 0 开始数。page - 1 就是在做这个翻译。
    # （忘了减 1 的后果：page=1 会跳过前 10 条，而且不报错，很难发现）

    start = (page - 1) * size
    # 返回一个字典，FastAPI 自动转成 JSON。四个字段各有用处：
    #   keyword / author → 原样回显，方便客户端核对「我传的是啥」
    #   total            → 过滤之后一共几条（注意是过滤后的，不是全部 4 条）
    #   data             → 这一页真正要显示的那几条
    #
    #   result[start : start + size]  是列表切片：从 start 位置开始，取 size 个。
    #     数据只有 4 条时，page=2&size=2 → 切出下标 2、3 两条，正好是第 3、4 本。
    #     越界也不会报错，Python 切片会「有多少给多少」，超出部分自动变成空。
    #
    # 实测 /book/search?page=2&size=2 的完整返回：
    #   {"keyword":"","author":"","total":4,
    #    "data":[{"id":3,"title":"计算机网络","author":"王五"},
    #            {"id":4,"title":"网络安全","author":"赵六"}]}

    return {"keyword": keyword, "author": author, "total": len(result), "data": result[start:start + size]}

# ============================================================================
# 路由三：GET /book/{book_id}  ——  路径参数（在网址里挖一个洞）
# ----------------------------------------------------------------------------
# {book_id} 就是那个洞。客户端在网址里填什么，函数就原样收到什么：
#     /book/2   →  book_id = 2
#     /book/7   →  book_id = 7
#
# 下面 def 里标了 :int，所以这里填的东西必须是整数，填 /book/abc 会被拦住：
#     422，type int_parsing，input "abc"      ← 实测
# 注意这个 422 是框架发的，你的函数一行都没跑。
# ============================================================================

# 函数参数名必须跟网址里那个洞的名字「一字不差」：
#     @app.get("/book/{book_id}")   配   def get_book(book_id:int)
#     写成 def get_book(bookid:int) —— 框架找不到 bookid 的值从哪来，启动就报错。
#
# ⚠️ 顺带一个你可能没注意的现象：上面路由一的函数叫 def get_book()，
#    这里的函数也叫 def get_book(book_id:int)，两个重名了，第二个把第一个覆盖了。
#    但它俩都正常工作 —— 因为 @app.get 在「定义的那一刻」就已经把函数登记进路由表了，
#    之后这个名字被谁顶掉，都不影响已经登记好的那条路。
#    （能跑，但别学：名字重复会让以后调试时找不到人，最好一个函数一个名字。）

@app.get("/book/{book_id}")
def get_book(book_id:int):
    # 遍历所有书，找 id 对上的那一本。

    for b in books:
        # == 判断「是否相等」；= 是「赋值」。这里必须是 ==，写成 = 会直接语法错误。

        if b["id"] == book_id:
            # 找到了就返回这一本，函数到此结束 —— 下面的 return 不会再执行。

            return b
    # 循环跑完还没 return，说明一本都没匹配上。
    #
    # 这里选择「返回 200 + 一句提示」，所以实测 GET /book/99 是 200，不是 404。
    # 这是当前阶段故意的（本节还没学 raise）—— 到 03 文件你会学到：
    #   找不到就用 raise HTTPException(status_code=404, ...) 抛一个 404，
    #   那才是真实项目里「详情接口」该有的样子。
    #
    # f"..." 是 f-string，把 {book_id} 替换成实际值：id 是 99 就输出「没有 id=99 的书」。

    return {"message": f"没有 id={book_id} 的书"}

# ============================================================================
# 启动段：直接运行 python 02_路由与参数.py 就能把服务起起来
# ----------------------------------------------------------------------------
# if __name__ == "__main__": 的意思是「只有直接运行这个文件时才执行下面三层」；
# 被别人 import 时（uvicorn 启动走的正是 import 这条路）不会重复起服务。
#
# 启动后：
#     服务地址   http://127.0.0.1:8000
#     接口文档   http://127.0.0.1:8000/docs     ← 本节所有接口都在这里点着测
# ============================================================================

# 启动服务
if __name__ == "__main__":
    # 局部导入 uvicorn：只有真的要启动服务时才需要它。

    import uvicorn
    # host=127.0.0.1 表示只允许本机访问（手机/别的电脑连不进来）；
    # port=8000 是端口号，被占用了会报 Errno 10048，换个 8001 / 8002 就行。

    uvicorn.run(app,host="127.0.0.1",port=8000)

# ============================================================================
# 【小结一：3 种传参方式一张表】
# ----------------------------------------------------------------------------
#              网址长什么样            函数怎么写            什么场景用
#   静态路由    /book                  def f()               只要全部数据
#   查询参数    /book/search?k=v       def f(k:str="")       过滤 / 排序 / 分页
#   路径参数    /book/2                def f(id:int)         指定某一个资源
#
# 【小结二：本节 3 个最值钱的结论】
#   1. 路由声明顺序 = 匹配顺序，具体的一定写在模糊的前面，否则被 422 吃掉。
#   2. 查询参数有没有默认值，决定它是否必填；空字符串 "" 让「不填 = 全都要」成立。
#   3. :int / :str 在 FastAPI 里是真校验，这也是它跟普通 Python 函数最大的不同。
#
