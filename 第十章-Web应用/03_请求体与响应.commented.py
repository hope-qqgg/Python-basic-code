#
# 【小结三：本节 3 个最值钱的结论】
#   1. 返回一条用 XXX，返回一堆用 list[XXX] —— 写反就是 500。
#   2. response_model 是出门安检：存什么和给外面看什么是两件事。
#   3. global 只管「写」：函数里一旦给全局变量赋值，就必须先 global。
#
