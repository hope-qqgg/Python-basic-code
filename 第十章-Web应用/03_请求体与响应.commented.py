#
# 【小结二：状态码速查（本章够用了）】
#    200  成功
#    201  成功，而且新建了东西（POST 新增用它）
#    404  找不到（raise HTTPException 主动抛）
#    422  参数类型不对 / 必填项没给（框架自动回，你不用写一行代码）
