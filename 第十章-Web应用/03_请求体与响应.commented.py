# ① Pydantic 是 FastAPI 背后的「校验库」。所有描述数据形状的类都要继承 BaseModel。

from pydantic import BaseModel
# ② HTTPException 用来主动抛 4xx/5xx（本文件第 37 行会用到）。
#    FastAPI 和 HTTPException 从同一个包里导入，一行写完。

from fastapi import FastAPI, HTTPException

# ③ 创建 app（和 02 完全一样，一张空的登记表）。

app = FastAPI()

# ============================================================================
# 请求体模型：Book —— 描述「客户端 POST 上来的那份 JSON 长什么样」
# ----------------------------------------------------------------------------
# 这个类不参与任何运算，它只干一件事：校验。
#     title: str           → 必须有，且必须是字符串
#     author: str          → 必须有
#     price: float = 0.0   → 有默认值 = 可以不传；不传就当 0.0
#
# 实测四种 body 的结局：
#   {"title":"x","author":"y","price":30}     →  201  正常新增
#   {"title":"x"}                             →  422  Field required（author 没给）
#   {"title":"x","author":"y","price":"贵"}   →  422  float_parsing（类型不对）
#   {"title":"x","author":"y","stock":99}     →  201  多出来的 stock 被静默丢掉
#
# 这就是它的价值：脏数据根本进不到你的函数里，你在函数内可以放心大胆用。
# ============================================================================

class Book(BaseModel):
    # 没有默认值 = 必填。客户端少给一个就 422，add_book 根本不会被调用。

    title:str
    author:str
    # 有默认值 = 选填。不传这个字段，price 就是 0.0。
    # 注意写的是 0.0（带小数点）而不是 0 —— 上面标的是 float，给个 float 最稳。

    price:float = 0.0

# ============================================================================
# 响应模型：BookOut —— 描述「服务端吐出去的东西长什么样」
# ----------------------------------------------------------------------------
# 🔑 关键点：它故意不含 price。
#    数据里明明存着 price（见下面 books），但只要从 BookOut 出去，price 就消失。
#
#    实测对照：
#      内存里实际是   {"id":1,"title":"Python编程","author":"张三","price":59.9}
#      客户端收到的是 [{"id":1,"title":"Python编程","author":"张三"}]     ← price 没了
#
# 这就是 response_model 的用处：**存什么和给外面看什么，是两件事**。
# 真实项目里，成本价、密码哈希、内部备注这些字段全靠它拦在门内。
# ============================================================================

class BookOut(BaseModel):      
    # id 也必须是必填 —— 万一你的返回里缺了 id，安检会直接报 500。
    # （响应模型既能「砍掉多的」，也能「要求少的」，是双向的。）

    id: int
    title: str
    author: str

# 假数据库（和 02 一样是内存列表，重启服务就只剩这一条）。
# 这一条特意带着 price —— 等下正好用它演示「price 被 BookOut 砍掉」。

books = [{"id": 1, "title": "Python编程", "author": "张三", "price": 59.9}]
# 自增编号的「下一个」。
# 现在列表里只有 id=1，所以下一本新书的编号应该是 2。
#
# ⚠️ 为什么不用 len(books) + 1 当下一个编号？
#    因为删过之后 len 会变小，编号就会重复（删了 1 之后 len=0，下一本又叫 1）。
#    用一个独立的计数器最稳，这也是真实项目里「自增主键」的思路。

next_id = 2

# ============================================================================
# 路由一：GET /book  ——  列表 + 响应模型过滤
# ----------------------------------------------------------------------------
# 这里的 response_model 写的是 list[BookOut]，因为你返回的是「一堆」书（列表），
# 每一条都按 BookOut 的形状出去。
#
#     实测：200，[{"id":1,"title":"Python编程","author":"张三"}]    ← price 不见了
#
# 记住这个对应关系（本文件最重要的判据）：
#     返回一堆  →  response_model=list[XXX]
#     返回一条  →  response_model=XXX
# ============================================================================

# 函数名起成 list_books 比 02 里那个 get_book 更贴切 —— 名字要说真话，
# 以后回头看代码，一眼就知道这个接口是「列一批」还是「取一条」。

@app.get("/book",response_model=list[BookOut])
def list_books():
    return books

# ============================================================================
# 路由二：POST /book  ——  新增一条（请求体 + 201）
# ----------------------------------------------------------------------------
# 这里一次出现三个新东西：
#   1. @app.post         → 只接受 POST。同一个网址 /book，GET 是「查」、POST 是「加」，
#                          网址一样、方法不一样 —— 这就是 REST 的核心思想。
#   2. response_model    → 控制返回的形状。
#   3. status_code=201   → 新增成功用 201，不是 200。
#                          200 是「请求成功」，201 是「请求成功，而且新建了东西」。
#
# 🔴🔴 【这一行有 bug —— 原文原样保留，你自己改】
#   你写的是 response_model=list[BookOut]，多套了一层 list[...]。
#   list[BookOut] 的意思翻译成人话是：「我要返回的是一个列表」。
#   可下面第 29 行 return item 返回的是「一条」字典。安检看你交了单个对象、
#   它要的是列表，于是直接抛异常。
#
#   实测（本机真跑）：
#     POST /book   {"title":"newbook","author":"zhaoliu","price":30}
#     →  500 Internal Server Error
#     服务端日志：
#       fastapi.exceptions.ResponseValidationError: 1 validation error:
#         {'type': 'list_type', 'loc': ('response',),
#          'msg': 'Input should be a valid list',
#          'input': {'id': 3, 'title': '新书', 'author': '赵六', 'price': 30.0}}
#
#   正确写法（只差去掉 list[...]）：
#     @app.post("/book", response_model=BookOut, status_code=201)
#
#   ⚠️ 还有一个更容易被忽略的后果：500 是在「返回阶段」才发生的，
#      那时函数体早就跑完了 —— 也就是说数据其实已经 append 进 books 了。
#      实测：POST 一次拿到 500，接着 GET /book 已经能看到那条新数据（id=2）。
#      这就是「脏数据悄悄进库、前端却以为失败」的典型样子，
#      也是为什么真实项目里要么保证返回模型对、要么用事务。
#
#   判断口诀：返回一条用 BookOut，返回一堆用 list[BookOut]。
#   另外注意 500 和 422 的区别：422 是客户端交的东西不对，500 是你自己的代码出错了。
# ============================================================================

# 参数类型写成 Book（上面那个模型）→ FastAPI 就去 HTTP 正文里读 JSON 来构造它。
# 这是它跟「查询参数」最本质的区别，只看参数类型：
#     参数类型是 BaseModel 的子类  →  去读请求体（body）
#     参数类型是 str / int 等      →  去读查询参数 或 路径参数

@app.post("/book",response_model=list[BookOut],status_code=201)
def add_book(book: Book):
    # ⭐ 为什么必须写 global？这是本节第二烧脑的地方。
    #
    #   函数里只要出现 "next_id = ..." 或 "next_id += 1" 这种「赋值」，
    #   Python 就会认定 next_id 是「这个函数自己的」局部变量，
    #   于是下面第 28 行 += 时，它去找一个还没被赋过值的局部变量 → 直接报错。
    #
    #   实测把 global 删掉跑一次：
    #     UnboundLocalError: cannot access local variable 'next_id'
    #                         where it is not associated with a value
    #
    #   global 的作用就是告诉 Python：「这个名字我指的是外面那个全局的，别自己造一个。」
    #   口诀：只读不写 → 不用 global；一旦要写（= / += / -= 都算）→ 必须 global。

    global next_id
    # ⭐ 这一行是本节最烧脑的一行，拆三层看。
    #    用 body {"title":"x","author":"y","price":30} 举例：
    #
    #   第 1 层   book                 → 一个 Book 对象，不是字典
    #                                     所以不能写 book["title"]，会报 TypeError
    #   第 2 层   book.model_dump()    → {'title':'x','author':'y','price':30.0}
    #                                     「对象 → 普通字典」就靠这一步，是 Pydantic 提供的
    #   第 3 层   **{...}              → 双星号是「摊开」：把这个字典的每一页
    #                                     拆出来，平铺进外层字典里
    #   拼完      结果                  → {'id':2,'title':'x','author':'y','price':30.0}
    #
    #   为什么要摊开，而不是写成 {"id": 2, "book": book}？
    #   因为后面所有代码都是 b["title"] 这种取法。写成嵌套的话，
    #   你就得写 b["book"]["title"]，而且 book 是对象不是字典，那样根本取不出来。

    item = {"id": next_id, **book.model_dump()}
    # 塞进「数据库」。注意这里是原地修改（append 改的是列表内部），
    # 并没有给 books 重新赋值 —— 所以这里不需要 global。

    books.append(item)
    # 计数器 +1，下一本新书就用新编号。
    # 这一行是「写」，全靠上面第 25 行的 global 才生效。

    next_id += 1
    # 返回这条新数据。它要能通过第 23 行 response_model 的检查 ——
    # 现在那行写的是 list[BookOut]，所以这里才会 500（详见上面那段注释）。

    return item


# ============================================================================
# 路由三：GET /book/{book_id}  ——  详情 + 真 404
# ----------------------------------------------------------------------------
# 外形和 02 的 /book/{book_id} 几乎一样，只差最后一行的处理方式：
#
#     02：找不到 → return {"message": ...}         → 状态码 200（假装成功）
#     03：找不到 → raise HTTPException(404, ...)   → 状态码 404（老实说没找到）
#
# 实测对比：
#     GET /book/1  →  200  {"id":1,"title":"Python编程","author":"张三"}
#     GET /book/9  →  404  {"detail":"没有 id=9 的书"}
#
# 🔑 为什么必须 raise，不能 return 一句提示？
#   调用方判断「成没成功」看的是状态码，不是正文里有没有「没有」这两个字。
#   你 return 一句"没有这本书"，状态码还是 200，对方会以为拿到了数据。
# ============================================================================

# 参数名 book_id 必须和网址里的 {book_id} 一字不差。

@app.get("/book/{book_id}", response_model=BookOut)
def get_book_by_id(book_id: int):
    # 和 02 一样：遍历列表，找 id 对上的那一条。

    for b in books:
        # 注意是 ==（相等判断），不是 =。这是最容易手滑的字符。

        if b["id"] == book_id:
            # 找到了就 return —— 这里是正常情况，用 return。

            return b
    # 循环跑完都没找到 → 主动抛 404。
    #
    #   raise   = 主动扔一个异常，FastAPI 接到之后回你指定的状态码，
    #             正文自动变成 {"detail": "你写的那句话"}
    #   return  = 正常返回（意味着 200）
    #
    # 抛出去之后函数立刻结束，下面的代码都不会执行。
    #
    # 两个参数：
    #   status_code=404           →  告诉调用方「你要的东西不存在」
    #   detail=f"没有 id={book_id} 的书"  →  给人看的一句话，会出现在返回的 detail 字段里

    raise HTTPException(status_code=404, detail=f"没有 id={book_id} 的书")

