# 启动段（和 02 完全一样）
#   服务地址   http://127.0.0.1:8000
#   接口文档   http://127.0.0.1:8000/docs
#
#   测 POST 最省事的办法就是 /docs：点 POST /book → Try it out，
#   它会按 Book 这个类自动生成一份 body 模板给你填，不用手写 JSON。
#   （这就是 BaseModel 白送的东西：你只写了类，文档自己长出来了。）
# ============================================================================

# 启动服务
if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app,host="127.0.0.1",port=8000)

