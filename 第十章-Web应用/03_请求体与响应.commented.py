# 【这个文件在干什么】
#   02 那课解决的是「客户端怎么把条件告诉服务端」（查询参数、路径参数），
#   可那两种只能传一两个简单的值。要让客户端「交一份完整资料」上来
#   （新增一本书：书名 + 作者 + 价格），就得用 POST + 请求体。
#   同时这一课还要解决反方向的一件事：返回时，哪些字段给外面看。
#
# 【两个方向、两个模型，千万别搞混】
#        方向              用哪个类     干嘛的
#        客户端 → 服务端    Book        描述「你交上来的资料长什么样」（请求体）
#        服务端 → 客户端    BookOut     描述「我吐出去的东西长什么样」（响应模型）
#    名字里的 In / Out 就是为了提醒方向；这里叫 Book / BookOut，一个意思。
#
# ⚠️ 一行重要说明：本文件里凡是提到「第 N 行」，指的都是【原文件
#    03_请求体与响应.py】的行号，不是这个注释版的行号（注释版插了注释，行号整体后移）。
#
# 【5 个新词】
#   1. BaseModel      —— Pydantic 的基类。继承它 = 「这个类负责校验数据形状」
#   2. 请求体(body)    —— POST 时放在 HTTP 正文里的 JSON，不在网址里
#   3. model_dump()   —— 把 pydantic 对象变成普通字典
#   4. response_model —— 出门安检：决定哪些字段能出现在返回里
#   5. HTTPException  —— 主动抛一个错误状态码（比如 404），而不是 return 一句话
#
# 🔴 【先说一个真问题，别照着抄】
#   第 23 行写的是 response_model=list[BookOut]，这个是错的。
#   实测 POST /book → 500 Internal Server Error，服务端日志里写着
#     ResponseValidationError: Input should be a valid list
#   正确写法是 response_model=BookOut（去掉外层的 list[...]），原因见那一行的注释。
#   本文件为了「逐字保留原文」没有改它，你自己改的时候记得动手。
